"""HealthcareGuard FastAPI application.

Run locally with: uvicorn server:app --reload
Deploy on Render with: uvicorn server:app --host 0.0.0.0 --port $PORT
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import List

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse
from pydantic import BaseModel, Field

from healthcareguard.guard import Guard
from healthcareguard.policy import ActionContext, ROLES, SOURCES
from healthcareguard.patient_risk import detect_patient_risk

APP_VERSION = "2.1.0-prototype"
app = FastAPI(
    title="HealthcareGuard API",
    description="Research prototype for screening healthcare prompts for safeguard-bypass and patient-risk signals.",
    version=APP_VERSION,
    docs_url="/api/docs",
    redoc_url=None,
)

allowed_origins = [x.strip() for x in os.getenv("ALLOWED_ORIGINS", "https://secframework.vercel.app").split(",") if x.strip()]
app.add_middleware(
    CORSMiddleware,
    allow_origins=allowed_origins,
    # Chrome extension IDs are generated by Chrome; its service worker also needs
    # host permission for the selected API domain in manifest.json.
    allow_origin_regex=r"chrome-extension://[a-p]{32}",
    allow_methods=["GET", "POST", "OPTIONS"],
    allow_headers=["Content-Type", "Authorization"],
    max_age=600,
)

# Load the existing trained model once per warm instance. Never train at cold start.
# If the artifact is missing or incompatible, report degraded status and refuse screening.
guard = None
guard_load_error = None
model_inference_error = None
try:
    guard = Guard.load()
    # Exercise the real classifier once during cold start using a synthetic,
    # non-patient education prompt. This catches cases where the artifact loads
    # but cannot perform inference in the deployed Python environment.
    guard.screen("What is diabetes?", ActionContext())
except Exception as exc:
    guard = None
    guard_load_error = type(exc).__name__
    model_inference_error = type(exc).__name__


class ScreenRequest(BaseModel):
    text: str = Field(..., min_length=1, max_length=4000)
    role: str = "unknown"
    verified: bool = False
    source: str = "user"
    flags: List[str] = Field(default_factory=list)


@app.get("/api/health")
def health():
    return {
        "ok": True,
        "status": "ready" if guard is not None else "degraded",
        "service": "HealthcareGuard",
        "version": APP_VERSION,
        "model_loaded": guard is not None,
        "safeguard_bypass_threshold": guard.threshold if guard is not None else None,
        "detectors": {
            "clinical_safeguard_model": "ready" if guard is not None else "unavailable",
            "patient_risk_rules": "ready",
        },
        "model_load_error": guard_load_error,
        "model_inference": "ready" if guard is not None and model_inference_error is None else "unavailable",
        "patient_risk_screening": "transparent_rules_v1",
        "note": "Research prototype; not clinically validated.",
    }


@app.post("/api/screen")
def screen(req: ScreenRequest):
    if guard is None:
        raise HTTPException(status_code=503, detail="The clinical safeguard model is unavailable. This prompt was not screened.")
    text = req.text.strip()
    if not text:
        raise HTTPException(status_code=422, detail="Enter text to screen.")

    context = ActionContext(
        actor_role=req.role if req.role in ROLES else "unknown",
        authorisation_verified=req.verified,
        content_source=req.source if req.source in SOURCES else "user",
        patient_flags=req.flags[:5],
    )

    # Keep the original model's complete verdict schema for compatibility.
    safeguard_result = guard.screen(text, context).as_dict()
    patient_risk = detect_patient_risk(text)

    urgent = patient_risk["level"] == "urgent"
    block = safeguard_result["decision"] == "BLOCK"
    high = patient_risk["level"] == "high" or safeguard_result["risk"] == "High"
    review = patient_risk["level"] == "review" or safeguard_result["decision"] == "REVIEW"
    should_alert = bool(patient_risk["detected"] or safeguard_result["flagged"] or safeguard_result["decision"] in ("BLOCK", "REVIEW"))

    if urgent:
        alert_level = "urgent"
        alert_title = "Urgent healthcare risk signal"
        alert_summary = "This prompt may describe an emergency or overdose. Do not wait for an AI response; seek urgent real-world help."
    elif block:
        alert_level = "high"
        alert_title = "Clinical safeguard bypass detected"
        alert_summary = safeguard_result["explanation"]
    elif high:
        alert_level = "high"
        alert_title = "Potential healthcare risk detected"
        alert_summary = "Review the medication or allergy concern with an appropriate healthcare professional."
    elif should_alert or review:
        alert_level = "review"
        alert_title = "Healthcare prompt needs review"
        alert_summary = "A pattern associated with a medication or clinical safety concern was detected."
    else:
        alert_level = "clear"
        alert_title = "No listed risk pattern detected"
        alert_summary = "No configured pattern was matched. This does not establish that the prompt or a later AI response is safe."

    safeguard_result["patient_risk"] = patient_risk
    safeguard_result["combined_alert"] = {
        "alert": should_alert,
        "level": alert_level,
        "title": alert_title,
        "summary": alert_summary,
    }
    safeguard_result["screening_disclaimer"] = (
        "HealthcareGuard is an experimental prompt-screening aid. It is not a medical device, "
        "does not provide diagnosis or triage, does not verify drug interactions, and cannot guarantee safety. "
        "Do not enter identifiable patient information."
    )
    return safeguard_result


@app.get("/")
def index():
    dashboard = Path(__file__).parent / "index.html"
    if dashboard.is_file():
        return FileResponse(dashboard)
    return {"service": "HealthcareGuard API", "docs": "/api/docs", "health": "/api/health"}


@app.get("/extension")
def extension_info():
    guide = Path(__file__).parent / "install.html"
    if guide.is_file():
        return FileResponse(guide)
    return {"message": "Extension install guide is not included in this deployment."}
